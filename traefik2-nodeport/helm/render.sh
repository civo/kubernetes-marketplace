#!/usr/bin/env bash
# Renders ../app.yaml from the upstream Traefik Helm chart and ./values.yaml.
# The marketplace applies app.yaml with kubectl (no Helm), so the output must be
# self-contained: CRDs are included and Helm ownership labels are stripped.
set -euo pipefail

CHART_VERSION="27.0.2" # last chart line for Traefik v2.11
HERE="$(cd "$(dirname "$0")" && pwd)"
APP_DIR="$(dirname "$HERE")"

helm repo add traefik https://traefik.github.io/charts >/dev/null 2>&1 || true
helm repo update traefik >/dev/null

{
  echo "# Generated by helm/render.sh from traefik/traefik chart ${CHART_VERSION}. Do not edit by hand."
  helm template traefik traefik/traefik \
    --version "${CHART_VERSION}" \
    --namespace kube-system \
    --include-crds \
    --values "${HERE}/values.yaml" |
    grep -v -E '^\s*(helm\.sh/chart|app\.kubernetes\.io/managed-by):'
} >"${APP_DIR}/app.yaml"
